"""Generates reports/project_audit.md entirely from the real project files (no typed numbers)."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

BASE = Path(__file__).resolve().parent
sys.path.append(str(BASE))
import config
from generate_model_notebooks import MODELS

P = config.PROCESSED_DATA_DIR
full = pd.read_csv(P / "fatigue_7features.csv")
train = pd.read_csv(P / "train.csv")
test = pd.read_csv(P / "test.csv")
split = json.loads((P / "split_indices.json").read_text())
raw = pd.read_csv(next(config.RAW_DATA_DIR.glob("*.csv")))
CN = config.CLASS_NAMES
CC = config.CLASS_COLUMN
lines = []
w = lines.append


def table(rows, header):
    w("| " + " | ".join(header) + " |")
    w("|" + "|".join(["---"] * len(header)) + "|")
    for r in rows:
        w("| " + " | ".join(str(x) for x in r) + " |")
    w("")


def dist(df):
    vc = df[CC].value_counts().sort_index()
    return ", ".join(f"{CN[k]} {v} ({v/len(df):.2%})" for k, v in vc.items())


w("# Project Audit Report\n")
w("_Generated by `generate_audit.py` from the real files. The old 80/20 results are obsolete; everything below is the 70/30 athlete-grouped split._\n")

# ---------------- A
w("## A. Data and split\n")
table([
    ["Dataset file", f"`{next(config.RAW_DATA_DIR.glob('*.csv')).name}`"],
    ["Columns in raw dataset", raw.shape[1]],
    ["Rows before duplicate removal", split["rows_before_dedup"]],
    ["Exact duplicate rows removed (before split)", split["exact_duplicates_removed"]],
    ["Rows after duplicate removal", split["total_rows"]],
    ["Train / test rows", f"{len(train)} ({len(train)/len(full):.2%}) / {len(test)} ({len(test)/len(full):.2%})"],
    ["Split method", split["method"] + " (stratified on class, grouped by athlete)"],
    ["Random seed", split["random_state"]],
    ["Group/time columns present", "`athlete_id` (156 athletes), `session_id`; no date column"],
    ["Athletes shared by train and test", len(set(train.athlete_id) & set(test.athlete_id))],
    ["Identical 7-feature rows shared", len(pd.merge(train[config.FEATURE_COLUMNS], test[config.FEATURE_COLUMNS]))],
    ["Athletes train / test", f"{train.athlete_id.nunique()} / {test.athlete_id.nunique()}"],
], ["Item", "Value"])
w("Because of the athlete id, a plain random split could leak athletes; the grouped split removes that. Within-athlete time order (`session_id`) is not used, so sessions of one athlete are never split across train and test.\n")

# ---------------- B
w("## B. Feature extraction / feature set\n")
w("**Model inputs now (in order):** " + ", ".join(f"`{c}`" for c in config.FEATURE_COLUMNS) + " (the original 7; no added columns).\n")
used = set(config.FEATURE_COLUMNS) | {config.TARGET_COLUMN}
dropped = [c for c in raw.columns if c not in used]
reasons = {"athlete_id": "id (used only to group CV/split)", "session_id": "id", "injury_occurred": "outcome column (leaky)",
           "age": "demographic", "gender": "demographic", "bmi": "demographic", "sport_type": "demographic/context"}
table([[f"`{c}`", reasons.get(c, "not among the 7 approved inputs (not used)")] for c in dropped] +
      [[f"`{config.TARGET_COLUMN}`", "target (class is derived from it; never an input)"]], ["Dropped / excluded column", "Reason"])
fe = (BASE / "training" / "features_engineering.py").exists()
w(f"**Feature engineering:** `training/features_engineering.py` {'exists' if fe else 'does not exist'} (ratios, interactions, log), built from the 7 input columns only. "
  "It was only evaluated in `training/test_improvements.py` and is **not used by the three final models or the app yet**.\n")
w("**Missing values:** "
  + ", ".join(f"`{c}` train {int(train[c].isna().sum())} / test {int(test[c].isna().sum())}" for c in config.FEATURE_COLUMNS if train[c].isna().sum() or test[c].isna().sum())
  + ". Logistic Regression and Random Forest: median imputer inside the pipeline (fit on training folds only). XGBoost: NaN passed through. StandardScaler is used for Logistic Regression only.\n")
w("**Permutation importance (test, macro-F1 drop, 10 repeats):**\n")
imp = {}
for k in MODELS:
    d = pd.read_csv(config.MODELS_DIR / k / "permutation_importance.csv").set_index("feature")["importance_mean"]
    imp[k] = d
table([[f"`{f}`"] + [f"{imp[k][f]:.4f}" for k in MODELS] for f in imp["xgboost"].sort_values(ascending=False).index],
      ["Feature"] + [MODELS[k]["title"] for k in MODELS])

# ---------------- C
w("## C. Classes\n")
lo, hi = config.CLASS_THRESHOLDS["low_max"], config.CLASS_THRESHOLDS["moderate_max"]
table([[0, "Low", f"fatigue_index < {lo}"], [1, "Moderate", f"{lo} <= fatigue_index < {hi}"], [2, "High", f"fatigue_index >= {hi}"]],
      ["Code", "Class", "Rule"])
w(f"- Boundaries: {lo} and {hi}; Moderate band is **{hi-lo:.2f} index points** wide.")
w("- Target type: **multi-class (3 classes)**, created by cutting the continuous `fatigue_index`.")
w(f"- Full data: {dist(full)}\n- Train: {dist(train)}\n- Test: {dist(test)}\n")

# ---------------- D
w("## D. Balanced or unbalanced\n")
vc = full[CC].value_counts()
dev = max(abs(v / len(full) - 1 / 3) for v in vc) * 100
w(f"- Imbalance ratio (largest/smallest class): **{vc.max()/vc.min():.3f}**; largest deviation from 33.3%: {dev:.2f} points.")
w(f"- Verdict: **{'balanced' if dev <= 10 else 'unbalanced'}** (rule: every class within ~10 points of 33%). No class is meaningfully over- or under-represented.\n")

# ---------------- E
w("## E. Weighted or unweighted\n")
bp = {k: json.loads((config.MODELS_DIR / k / "best_params.json").read_text()) for k in MODELS}
table([
    ["Logistic Regression", "`class_weight` searched over [None, 'balanced']", f"chosen: `{bp['logistic_regression'].get('class_weight')}`"],
    ["Random Forest", "`class_weight` not set", "unweighted"],
    ["XGBoost", "no `sample_weight` passed", "unweighted"],
], ["Model", "Weighting", "Result"])
w("Accuracy is not weighted. Precision/recall/F1 are reported both **macro** (unweighted class mean, used for selection) and **weighted** (by class support).\n")

# ---------------- F
w("## F. Hyperparameters\n")
w("All three: `GridSearchCV`, 5-fold `StratifiedGroupKFold` (grouped by athlete, train only), scoring macro-F1 (accuracy also recorded). No RandomizedSearchCV yet.\n")
fixed = {
    "logistic_regression": "fixed: penalty=l2 (default), max_iter=1000",
    "random_forest": "fixed: max_features='sqrt' (default)",
    "xgboost": "not searched (defaults): min_child_weight=1, gamma=0, reg_alpha=0, reg_lambda=1",
}
for k, m in MODELS.items():
    ns = {}
    exec(m["grid"], ns)
    grid = ns["param_grid"]
    met = pd.read_csv(config.MODELS_DIR / k / "metrics.csv").iloc[0]
    w(f"### {m['title']}\n")
    rows = []
    for p, vals in grid.items():
        name = p.replace(m["prefix"], "")
        best = bp[k][name]
        nums = [v for v in vals if isinstance(v, (int, float)) and not isinstance(v, bool)]
        edge = ""
        if len(vals) > 1 and best in vals:
            i = vals.index(best)
            if i in (0, len(vals) - 1) and len(nums) >= 2:
                edge = "**yes - on grid edge**"
            elif i in (0, len(vals) - 1):
                edge = "edge (categorical)"
            else:
                edge = "no"
        rows.append([f"`{name}`", vals, f"`{best}`", edge])
    table(rows, ["Parameter", "Search space", "Best", "On edge (range too narrow?)"])
    n_comb = int(np.prod([len(v) for v in grid.values()]))
    w(f"- Combinations: {n_comb} x 5 folds; best CV macro-F1 **{met.cv_macro_f1:.4f}**, CV accuracy **{met.cv_accuracy:.4f}**. {fixed[k]}.\n")

# ---------------- G
w("## G. Current stage and results\n")
done = {
    "Data inspection (`00_inspect_dataset.py`)": (BASE / "training" / "00_inspect_dataset.py").exists(),
    "Data preparation, 70/30 grouped split": (P / "split_indices.json").exists(),
    "Three trainings (notebooks 01-03)": all((config.MODELS_DIR / k / "metrics.csv").exists() for k in MODELS),
    "Selection (`05_select_best_model.py`)": (config.MODELS_DIR / "selected_model.json").exists(),
    "Flask app": (BASE / "app" / "app.py").exists(),
    "Tests": (BASE / "tests" / "test_fatigue_app.py").exists(),
    "README": (BASE / "README.md").exists(),
}
table([[k, "present" if v else "missing"] for k, v in done.items()], ["Stage", "Status"])
w("_Note: tests, README and app numbers were built for the old 80/20 run and have **not** been re-verified on the 70/30 results yet._\n")
rows = []
for k, m in MODELS.items():
    r = pd.read_csv(config.MODELS_DIR / k / "metrics.csv").iloc[0]
    t = pd.read_csv(config.MODELS_DIR / k / "wall_time.csv").iloc[0]
    rows.append([m["title"], f"{r.train_accuracy:.4f}", f"{r.cv_accuracy:.4f}", f"{r.accuracy:.4f}", f"{r.f1_macro:.4f}",
                 f"{r.roc_auc_ovr:.4f}", f"{t.total_training_wall_time_s:.1f}s (fit only {t.fit_wall_time_seconds:.3f}s)",
                 f"{t.prediction_time_per_1k_ms:.2f} ms", f"{r.train_accuracy - r.cv_accuracy:+.4f}"])
table(rows, ["Model", "Train acc", "CV acc", "Test acc", "Macro-F1", "ROC-AUC", "Training wall time", "Predict /1k rows", "Gap (train - CV)"])
sel = json.loads((config.MODELS_DIR / "selected_model.json").read_text())
accs = {m["title"]: pd.read_csv(config.MODELS_DIR / k / "metrics.csv").iloc[0].accuracy for k, m in MODELS.items()}
w(f"**Status:** the pipeline is built end to end; the data and models are rebuilt on the 70/30 grouped split. Accuracy is about "
  f"{min(accs.values()):.1%}-{max(accs.values()):.1%} for all three models (target 80-85%, not met). The three very different model families "
  f"land within about {(max(accs.values())-min(accs.values()))*100:.1f} points of each other and CV matches test, so this is not a tuning or leakage issue; "
  "the 7 inputs do not determine the class (the continuous R-squared check is the first step of Part 3). "
  f"Random Forest overfits (gap {rows[1][-1]}), the others do not. Currently selected: `{sel.get('model_name')}`.\n")

out = config.REPORTS_DIR / "project_audit.md"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"Saved {out}")
